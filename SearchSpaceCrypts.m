function [lowlimit, upperlimit] = SearchSpaceCrypts(number_of_bodies)

%*******************************************************************************
% SEARCH SPACE DEFINITION (TRNAVA DATASET)
%
% Purpose:
%   Defines the lower and upper bounds for the PSO search space based on 
%   the number of anomalous bodies (2, 4, or 6) for the Trnava crypts dataset.
%
% Authors:
%   GPINV Research Group
%   University of Oviedo, Spain
%
% Copyright (c) 2026 GPINV Research Group, University of Oviedo
%
% This code is licensed under the MIT License. 
% See the LICENSE file in the project root for more information.
%*******************************************************************************

switch number_of_bodies

    %==============================================================
    % 2 CUERPOS
    %==============================================================
    case 2

        lowlimit = [ ...
            85 92 -2.5 0.5 0.5 0 0 -2200,...
            85 88 -2.5 0.5 0.5 0 0 -2200];

        upperlimit = [ ...
            87 94 -1.0 1.5 1.5 180 90 -1200,...
            87 90 -1.0 1.5 1.5 180 90 -1200];

    %==============================================================
    % 4 CUERPOS
    %==============================================================
    case 4

        lowlimit = [ ...
            85 92.0 -2.5 0.5 0.5 0 0 -2200,...
            85 87.5 -2.5 0.5 0.5 0 0 -2200,...
            85 92.0 -2.5 0.3 0.3 0 0 -2200,...
            85 87.5 -2.5 0.3 0.3 0 0 -2200];

        upperlimit = [ ...
            87 94.5 -1.0 1.5 1.5 180 15 -1200,...
            87 89.5 -1.0 1.5 1.5 180 15 -1200,...
            87 94.5 -1.0 1.0 1.0 180 15 -1200,...
            87 89.5 -1.0 1.0 1.0 180 15 -1200];

    %==============================================================
    % 6 CUERPOS
    %==============================================================
    case 6

        lowlimit = [ ...
            85 92.0 -2.5 0.5 0.5 0 0 -2200,...
            85 92.0 -2.5 0.2 0.2 0 0 -2200,...
            85 92.0 -2.5 0.2 0.2 0 0 -2200,...
            85 87.5 -2.5 0.5 0.5 0 0 -2200,...
            85 87.5 -2.5 0.2 0.2 0 0 -2200,...
            85 87.5 -2.5 0.2 0.2 0 0 -2200];

        upperlimit = [ ...
            87 94.5 -1.0 1.5 1.5 180 15 -1200,...
            87 94.5 -1.0 0.8 0.8 180 15 -1200,...
            87 94.5 -1.0 0.8 0.8 180 15 -1200,...
            87 89.5 -1.0 1.5 1.5 180 15 -1200,...
            87 89.5 -1.0 0.8 0.8 180 15 -1200,...
            87 89.5 -1.0 0.8 0.8 180 15 -1200];

    otherwise

        error('Número de cuerpos no soportado.');

end